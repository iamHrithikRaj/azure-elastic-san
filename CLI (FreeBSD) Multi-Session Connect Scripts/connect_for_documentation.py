def create_argument_parser():
    parser = argparse.ArgumentParser(
        description=(
            "Connect one or more Azure Elastic SAN volumes with multiple iSCSI sessions on "
            "FreeBSD 13+, using the native iscsid/iscsictl initiator."
        )
    )
    parser.add_argument(
        "--elastic-san-subscription",
        "--subscription",
        dest="elastic_san_subscription",
        help=(
            "Elastic SAN resource subscription name or ID. --subscription is retained as a "
            "compatibility alias."
        ),
    )
    parser.add_argument("-g", "--resource-group", dest="resource_group")
    parser.add_argument("-e", "--elastic-san", dest="elastic_san")
    parser.add_argument("-v", "--volume-group", dest="volume_group")
    parser.add_argument("-n", "--volumes", dest="volumes", nargs="+")
    parser.add_argument("-s", "--num-of-sessions", dest="num_of_sessions")
    parser.add_argument(
        "--enable-zonal-affinity",
        action="store_true",
        help=(
            "Opt in to provisional logical-to-physical availability-zone routing. Requires "
            "Elastic SAN front-end support for parsing the IQN suffix."
        ),
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help=(
            "Perform all read-only discovery/mapping/config planning and print the plan, "
            "without running sysrc, service, or iscsictl, and without writing "
            + DEFAULT_ISCSI_CONF_PATH
            + ". Does not require root. Existing session counts are not inspected in this mode "
            "(inspecting them requires root); the plan assumes zero pre-existing sessions."
        ),
    )
    parser.add_argument(
        "--config-path",
        dest="config_path",
        default=DEFAULT_ISCSI_CONF_PATH,
        help=argparse.SUPPRESS,  # override for tests only; not part of the public CLI contract
    )
    return parser


def main(argv=None):
    parser = create_argument_parser()
    args = parser.parse_args(sys.argv[1:] if argv is None else argv)

    resource_group_name = args.resource_group
    elastic_san_name = args.elastic_san
    volume_group_name = args.volume_group
    volume_names = args.volumes
    # default is 32, also the maximum allowed number of sessions; validate this against your
    # environment's iSCSI/network limits (see README.md) before relying on the default.
    number_of_sessions = (
        min(32, int(args.num_of_sessions)) if args.num_of_sessions is not None else 32
    )

    if None in (resource_group_name, elastic_san_name, volume_group_name, volume_names):
        raise ElasticSanConnectError(
            "Need to provide resource_group_name, elastic_san_name, volume_group_name, "
            "volume_names to connect to the Elastic SAN volume(s)"
        )
    if number_of_sessions < 1:
        raise ElasticSanConnectError(
            "--num-of-sessions must be at least 1 (got {})".format(number_of_sessions)
        )

    check_az_cli_available()

    plans = build_connection_plan(
        args.elastic_san_subscription,
        resource_group_name,
        elastic_san_name,
        volume_group_name,
        volume_names,
        number_of_sessions,
        args.enable_zonal_affinity,
    )

    if args.dry_run:
        print("[dry-run] No mutating commands (sysrc/service/iscsictl) will be run.")
        for line in describe_plan(plans, number_of_sessions):
            print("[dry-run] " + line)
        print(
            "[dry-run] Would write the following managed block to {}:".format(args.config_path)
        )
        print(render_full_managed_block(plans).decode("utf-8"))
        return

    execute_connection_plan(plans, args.config_path, number_of_sessions)


if __name__ == "__main__":
    main()
