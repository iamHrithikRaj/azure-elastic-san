def validate_config_scalar(value, field_name):
    """Reject anything that could inject a new statement/stanza into
    iscsi.conf(5) (quotes, braces, comment/statement separators, or control
    characters including newlines) rather than attempting to escape it --
    the format has no documented escape sequence for these characters."""
    if not isinstance(value, string_types) or not value:
        raise ElasticSanConnectError("{} must be a non-empty string".format(field_name))
    if any(ord(character) < 0x20 for character in value):
        raise ElasticSanConnectError(
            "{} contains a control character, which is not permitted in an iscsi.conf "
            "value".format(field_name)
        )
    if any(character in _FORBIDDEN_CONFIG_CHARS for character in value):
        raise ElasticSanConnectError(
            "{} contains one of {} which is not permitted in an iscsi.conf value: {!r}".format(
                field_name, sorted(_FORBIDDEN_CONFIG_CHARS), value
            )
        )
    return value


def sanitize_identity_component(value, field_name):
    if not isinstance(value, string_types) or not value.strip():
        raise ElasticSanConnectError("{} must be a non-empty string".format(field_name))
    lowered = value.strip().lower()
    sanitized = re.sub(r"[^a-z0-9]+", "-", lowered).strip("-")
    if not sanitized:
        raise ElasticSanConnectError(
            "{} '{}' has no [a-z0-9] characters left to build a config nickname from".format(
                field_name, value
            )
        )
    return sanitized


def build_nickname(volume_group_name, volume_name, target_name, session_index):
    """Deterministic, collision-resistant iscsi.conf nickname for one
    (volume group, volume, target IQN, session index) tuple.

    The SHA-256 input is the UTF-8 encoding of a compact JSON array containing
    the raw (unsanitized) values. JSON's string lengths/escaping and array
    boundaries make the identity unambiguous, while matching JSON.stringify
    in the Azure portal implementation.
    """
    sanitized_group = sanitize_identity_component(volume_group_name, "Volume group name")
    sanitized_volume = sanitize_identity_component(volume_name, "Volume name")
    if not isinstance(target_name, string_types) or not target_name:
        raise ElasticSanConnectError("Target IQN must be a non-empty string")
    if session_index != 1:
        raise ElasticSanConnectError(
            "Stock FreeBSD supports exactly one session per Elastic SAN volume in this PoC"
        )

    readable_base = "esan-{}-{}".format(sanitized_group, sanitized_volume)
    identity_json = json.dumps(
        [volume_group_name, volume_name, target_name, session_index],
        ensure_ascii=False,
        separators=(",", ":"),
    )
    identity_hash = hashlib.sha256(identity_json.encode("utf-8")).hexdigest()[:16]
    suffix = "-{}-s1".format(identity_hash)
    readable_prefix = readable_base[: 128 - len(suffix)].rstrip("-")
    nickname = readable_prefix + suffix

    if len(nickname) > 128 or NICKNAME_PATTERN.match(nickname) is None:
        raise ElasticSanConnectError(
            "Generated nickname '{}' is not a safe iscsi.conf identifier (volume group/volume "
            "names may resolve to no usable characters)".format(nickname)
        )
    return nickname


class ManagedConfigEntry(object):
    __slots__ = ("nickname", "target_name", "target_address")

    def __init__(self, nickname, target_name, target_address):
        self.nickname = nickname
        self.target_name = target_name
        self.target_address = target_address


def render_managed_block(entries):
    """Render the full managed block (including BEGIN/END markers) for the
    given ManagedConfigEntry list. TargetName/TargetAddress are pre-validated
    by validate_config_scalar, so quoting them here cannot be broken out of."""
    lines = [MANAGED_BLOCK_BEGIN]
    for entry in entries:
        lines.append("{} {{".format(entry.nickname))
        lines.append('\tTargetName    = "{}"'.format(entry.target_name))
        lines.append('\tTargetAddress = "{}"'.format(entry.target_address))
        lines.append("\tHeaderDigest  = CRC32C")
        lines.append("\tDataDigest    = CRC32C")
        lines.append("\tEnable        = On")
        lines.append("}")
    lines.append(MANAGED_BLOCK_END)
    return ("\n".join(lines) + "\n").encode("utf-8")


_TARGET_NAME_LINE = re.compile(r'^\tTargetName    = "([^"]+)"$')
_TARGET_ADDRESS_LINE = re.compile(r'^\tTargetAddress = "([^"]+)"$')


def parse_managed_block(managed_block_bytes):
    """Strictly parse a block emitted by render_managed_block.

    Unknown, reordered, missing, or duplicate content is rejected so a rerun
    cannot silently discard a stanza that an operator or another generator
    placed between the shared markers.
    """
    try:
        text = managed_block_bytes.decode("utf-8")
    except UnicodeDecodeError as error:
        raise ElasticSanConnectError(
            "The Azure Elastic SAN managed block is not valid UTF-8: {}".format(error)
        )

    lines = text.splitlines()
    if (
        len(lines) < 2
        or lines[0] != MANAGED_BLOCK_BEGIN
        or lines[-1] != MANAGED_BLOCK_END
    ):
        raise ElasticSanConnectError(
            "The Azure Elastic SAN managed block does not have exact BEGIN/END marker lines"
        )

    entries = []
    seen_nicknames = set()
    index = 1
    while index < len(lines) - 1:
        if index + 6 >= len(lines):
            raise ElasticSanConnectError(
                "The Azure Elastic SAN managed block contains incomplete or unknown content"
            )
        nickname_line = lines[index]
        if not nickname_line.endswith(" {"):
            raise ElasticSanConnectError(
                "The Azure Elastic SAN managed block contains unknown content: {!r}".format(
                    nickname_line
                )
            )
        nickname = nickname_line[:-2]
        target_name_match = _TARGET_NAME_LINE.match(lines[index + 1])
        target_address_match = _TARGET_ADDRESS_LINE.match(lines[index + 2])
        expected_tail = [
            "\tHeaderDigest  = CRC32C",
            "\tDataDigest    = CRC32C",
            "\tEnable        = On",
            "}",
        ]
        if (
            NICKNAME_PATTERN.match(nickname) is None
            or target_name_match is None
            or target_address_match is None
            or lines[index + 3 : index + 7] != expected_tail
        ):
            raise ElasticSanConnectError(
                "The Azure Elastic SAN managed block entry starting at {!r} is malformed or "
                "contains unknown content".format(nickname_line)
            )
        if nickname in seen_nicknames:
            raise ElasticSanConnectError(
                "The Azure Elastic SAN managed block contains duplicate nickname '{}'".format(
                    nickname
                )
            )
        seen_nicknames.add(nickname)
        entries.append(
            ManagedConfigEntry(
                nickname,
                validate_config_scalar(target_name_match.group(1), "Managed TargetName"),
                validate_config_scalar(
                    target_address_match.group(1), "Managed TargetAddress"
                ),
            )
        )
        index += 7
    return entries


