def validate_config_scalar(value, field_name):
    """Reject anything that could inject a new statement/stanza into
    iscsi.conf(5) (quotes, braces, comment/statement separators, or control
    characters including newlines) rather than attempting to escape it --
    the format has no documented escape sequence for these characters."""
    if not isinstance(value, string_types) or not value:
        raise ElasticSanConnectError("{} must be a non-empty string".format(field_name))
    if any(ord(character) < 0x20 for character in value):
        raise ElasticSanConnectError(
            "{} contains a control character, which is not permitted in an iscsi.conf "
            "value".format(field_name)
        )
    if any(character in _FORBIDDEN_CONFIG_CHARS for character in value):
        raise ElasticSanConnectError(
            "{} contains one of {} which is not permitted in an iscsi.conf value: {!r}".format(
                field_name, sorted(_FORBIDDEN_CONFIG_CHARS), value
            )
        )
    return value


def sanitize_identity_component(value, field_name):
    if not isinstance(value, string_types) or not value.strip():
        raise ElasticSanConnectError("{} must be a non-empty string".format(field_name))
    lowered = value.strip().lower()
    sanitized = re.sub(r"[^a-z0-9]+", "-", lowered).strip("-")
    if not sanitized:
        raise ElasticSanConnectError(
            "{} '{}' has no [a-z0-9] characters left to build a config nickname from".format(
                field_name, value
            )
        )
    return sanitized


def build_nickname(volume_group_name, volume_name, session_index):
    """Deterministic, collision-resistant iscsi.conf nickname for one
    (volume group, volume, session index) tuple. Same inputs always produce
    the same nickname, which is what makes managed-block regeneration
    idempotent across re-runs."""
    sanitized_group = sanitize_identity_component(volume_group_name, "Volume group name")
    sanitized_volume = sanitize_identity_component(volume_name, "Volume name")
    nickname = "esan-{}-{}-s{}".format(sanitized_group, sanitized_volume, session_index)
    if NICKNAME_PATTERN.match(nickname) is None:
        raise ElasticSanConnectError(
            "Generated nickname '{}' is not a safe iscsi.conf identifier (volume group/volume "
            "names may be too long or resolve to no usable characters)".format(nickname)
        )
    return nickname


class ManagedConfigEntry(object):
    __slots__ = ("nickname", "target_name", "target_address")

    def __init__(self, nickname, target_name, target_address):
        self.nickname = nickname
        self.target_name = target_name
        self.target_address = target_address


def render_managed_block(entries):
    """Render the full managed block (including BEGIN/END markers) for the
    given ManagedConfigEntry list. TargetName/TargetAddress are pre-validated
    by validate_config_scalar, so quoting them here cannot be broken out of."""
    lines = [MANAGED_BLOCK_BEGIN]
    for entry in entries:
        lines.append("{} {{".format(entry.nickname))
        lines.append('\tTargetName    = "{}"'.format(entry.target_name))
        lines.append('\tTargetAddress = "{}"'.format(entry.target_address))
        lines.append("\tHeaderDigest  = CRC32C")
        lines.append("\tDataDigest    = CRC32C")
        lines.append("\tEnable        = On")
        lines.append("}")
    lines.append(MANAGED_BLOCK_END)
    return ("\n".join(lines) + "\n").encode("utf-8")


# ---------------------------------------------------------------------------
# /etc/iscsi.conf atomic update with backup/rollback
# ---------------------------------------------------------------------------

def _split_managed_block(content_bytes):
    """Return (prefix, suffix) byte spans surrounding any existing managed
    block in *content_bytes*, preserving everything else byte-for-byte. If no
    managed block markers are present, the whole file is treated as prefix
    (the new block is appended). Raises if exactly one marker is present,
    which indicates hand-edited/corrupted state we should not try to guess
    our way through."""
    begin_bytes = MANAGED_BLOCK_BEGIN.encode("utf-8")
    end_bytes = MANAGED_BLOCK_END.encode("utf-8")
    begin_index = content_bytes.find(begin_bytes)
    end_index = content_bytes.find(end_bytes)

    if begin_index == -1 and end_index == -1:
        return content_bytes, b""

    if begin_index == -1 or end_index == -1:
        raise ElasticSanConnectError(
            "{} contains only one of the managed-block BEGIN/END markers. Refusing to modify "
            "it automatically; restore the file from a backup or remove the stray marker line "
            "by hand before retrying.".format(DEFAULT_ISCSI_CONF_PATH)
        )
    if end_index < begin_index:
        raise ElasticSanConnectError(
            "{} has a managed-block END marker before its BEGIN marker. Refusing to modify it "
            "automatically.".format(DEFAULT_ISCSI_CONF_PATH)
        )

    end_line_terminator = content_bytes.find(b"\n", end_index)
    end_of_end_line = end_line_terminator + 1 if end_line_terminator != -1 else len(content_bytes)
    prefix = content_bytes[:begin_index]
    suffix = content_bytes[end_of_end_line:]

    # Guard against a second, stray marker pair further down the file (e.g.
    # from a manually concatenated/restored backup). We already refuse to
    # guess our way through a single stray marker above; a duplicate pair
    # deserves the same treatment rather than being silently preserved in
    # 'suffix' forever.
    if begin_bytes in suffix or end_bytes in suffix:
        raise ElasticSanConnectError(
            "{} contains more than one managed-block marker pair. Refusing to modify it "
            "automatically; remove the duplicate BEGIN/END markers by hand before "
            "retrying.".format(DEFAULT_ISCSI_CONF_PATH)
        )

    return prefix, suffix


def compute_new_config_content(existing_content_bytes, managed_block_bytes):
    prefix, suffix = _split_managed_block(existing_content_bytes)
    if prefix and not prefix.endswith(b"\n"):
        prefix += b"\n"
    return prefix + managed_block_bytes + suffix


def read_config_file(path):
    """Return (content_bytes, existed, stat_result_or_None)."""
    if not os.path.exists(path):
        return b"", False, None
    with open(path, "rb") as handle:
        content = handle.read()
    return content, True, os.stat(path)


def backup_config(path, existing_content_bytes, existed):
    """Write a backup of the current config content before mutating it.
    Returns the backup path (or None if the file did not exist yet, in which
    case there is nothing to back up)."""
    if not existed:
        return None
    backup_path = "{}.bak.pre-esan-connect.{}".format(path, os.getpid())
    directory = os.path.dirname(path) or "."
    fd, temp_path = tempfile.mkstemp(prefix=".iscsi.conf.bak.", dir=directory)
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(existing_content_bytes)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temp_path, backup_path)
    except BaseException:
        if os.path.exists(temp_path):
            os.remove(temp_path)
        raise
    return backup_path


def write_config_atomically(path, new_content_bytes, original_stat):
    """Write *new_content_bytes* to *path* atomically via a temp file in the
    same directory + os.replace, preserving the original file's permissions
    and ownership where possible."""
    directory = os.path.dirname(path) or "."
    fd, temp_path = tempfile.mkstemp(prefix=".iscsi.conf.new.", dir=directory)
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(new_content_bytes)
            handle.flush()
            os.fsync(handle.fileno())
        if original_stat is not None:
            os.chmod(temp_path, original_stat.st_mode & 0o7777)
            # Ownership preservation only applies on platforms that expose
            # os.chown (i.e. POSIX/FreeBSD, the only supported target for
            # this script) -- "where possible" per the design requirements.
            if hasattr(os, "chown"):
                try:
                    os.chown(temp_path, original_stat.st_uid, original_stat.st_gid)
                except OSError as error:
                    raise ElasticSanConnectError(
                        "Failed to preserve ownership of {} on the replacement file: {}".format(
                            path, error
                        )
                    )
        else:
            os.chmod(temp_path, 0o644)
        os.replace(temp_path, path)
    except BaseException:
        if os.path.exists(temp_path):
            os.remove(temp_path)
        raise


def restore_config_from_backup(path, backup_path, existed, original_stat):
    """Roll back a mutation: restore the pre-mutation content and permissions
    (or remove the file entirely if it did not exist before this run created
    it). *original_stat* must be the stat() of the file captured before it
    was mutated -- the backup file itself is deliberately created with
    restrictive permissions regardless of the original file's mode, since
    unrelated stanzas preserved outside the managed block may contain CHAP
    secrets."""
    if not existed:
        if os.path.exists(path):
            os.remove(path)
        return
    with open(backup_path, "rb") as handle:
        backup_content = handle.read()
    write_config_atomically(path, backup_content, original_stat)


