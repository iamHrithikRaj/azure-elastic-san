# These markers are intentionally origin-neutral (no "generated by <this script>" text): both
# this standalone script and the Azure portal's generated FreeBSD connect script write to the
# same /etc/iscsi.conf and must recognize/update each other's managed block rather than treating
# it as a stray, hand-edited marker. Keep this pair byte-for-byte identical to MANAGED_BLOCK_BEGIN
# / MANAGED_BLOCK_END in VolumeHelpers.ts's generateFreeBsdConnectScript.
MANAGED_BLOCK_BEGIN = "# BEGIN AZURE ELASTIC SAN FREEBSD MANAGED BLOCK -- DO NOT EDIT"
MANAGED_BLOCK_END = "# END AZURE ELASTIC SAN FREEBSD MANAGED BLOCK"

# Characters that would break the iscsi.conf(5) grammar or allow one
# configured value to inject a second statement/stanza.
_FORBIDDEN_CONFIG_CHARS = frozenset('"{}#;')
NICKNAME_PATTERN = re.compile(r"^[a-z0-9][a-z0-9_-]{0,127}$")


class ElasticSanConnectError(Exception):
    """Raised for any expected, actionable failure in this script."""


# ---------------------------------------------------------------------------
# Bounded subprocess execution (shared by Azure CLI and FreeBSD tool calls)
# ---------------------------------------------------------------------------

def _decode_output(value):
    return value.decode("utf-8") if isinstance(value, bytes) else value


def _run_subprocess(command, description, timeout):
    """Run *command* (an argv list; never a shell string) with a hard wall-clock
    timeout, returning (returncode, stdout, stderr). Never raises on a non-zero
    exit code -- callers decide whether that is fatal."""
    try:
        process = subprocess.Popen(command, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    except OSError as error:
        raise ElasticSanConnectError("{} failed to start: {}".format(description, error))

    result = []
    communication_errors = []

    def communicate():
        try:
            result.append(process.communicate())
        except (OSError, ValueError) as error:
            communication_errors.append(error)

    communication_thread = threading.Thread(target=communicate)
    communication_thread.daemon = True
    communication_thread.start()
    communication_thread.join(timeout)
    if communication_thread.is_alive():
        process.kill()
        communication_thread.join()
        raise ElasticSanConnectError(
            "{} timed out after {} seconds".format(description, timeout)
        )
    if communication_errors:
        raise ElasticSanConnectError(
            "{} failed while collecting output: {}".format(
                description, communication_errors[0]
            )
        )

    out, err = result[0]
    return process.returncode, _decode_output(out), _decode_output(err).strip()


def _run_command(command, description, timeout=AZ_CLI_TIMEOUT_SECONDS):
    """Run *command* and raise ElasticSanConnectError if it exits non-zero."""
    returncode, out, err = _run_subprocess(command, description, timeout)
    if returncode != 0:
        detail = err if err else "exit code {}".format(returncode)
        raise ElasticSanConnectError("{} failed: {}".format(description, detail))
    return out


def _run_az_command(command, description):
    return _run_command(command, description, AZ_CLI_TIMEOUT_SECONDS)


