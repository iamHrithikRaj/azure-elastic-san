def ensure_iscsid_enabled_and_running():
    current = _run_command(
        ["sysrc", "-n", "iscsid_enable"], "sysrc iscsid_enable query", SHORT_COMMAND_TIMEOUT_SECONDS
    )
    if current.strip().upper() != "YES":
        _run_command(
            ["sysrc", "iscsid_enable=YES"], "sysrc iscsid_enable=YES", SHORT_COMMAND_TIMEOUT_SECONDS
        )
    returncode, _, _ = _run_subprocess(
        ["service", "iscsid", "onestatus"], "service iscsid onestatus", SHORT_COMMAND_TIMEOUT_SECONDS
    )
    if returncode != 0:
        _run_command(
            ["service", "iscsid", "start"], "service iscsid start", SHORT_COMMAND_TIMEOUT_SECONDS
        )


# ---------------------------------------------------------------------------
# iscsictl session inspection/management
# ---------------------------------------------------------------------------

def list_iscsi_sessions():
    """Parse 'iscsictl -L -v' into a list of per-session field dicts (keys
    such as 'Target name', 'Target portal', 'Session state'). The nickname
    used to add a session is not part of the kernel's session state and is
    therefore not recoverable from this listing -- sessions are correlated
    by (Target name, Target portal) only."""
    output = _run_command(
        ["iscsictl", "-L", "-v"], "iscsictl session listing", AZ_CLI_TIMEOUT_SECONDS
    )
    return _parse_iscsictl_verbose_sessions(output)


def _parse_iscsictl_verbose_sessions(output):
    sessions = []
    for block in output.split("\n\n"):
        if not block.strip():
            continue
        fields = {}
        for line in block.splitlines():
            if ":" not in line:
                continue
            label, _, value = line.partition(":")
            fields[label.strip()] = value.strip()
        if "Target name" in fields and "Target portal" in fields:
            sessions.append(fields)
    return sessions


def count_matching_sessions(sessions, target_name, target_address):
    return sum(
        1
        for session in sessions
        if session.get("Target name") == target_name
        and session.get("Target portal") == target_address
    )


def add_iscsi_session(nickname, config_path):
    command = [
        "iscsictl",
        "-A",
        "-n",
        nickname,
        "-c",
        config_path,
        "-w",
        str(ISCSICTL_SESSION_WAIT_SECONDS),
    ]
    _run_command(
        command, "iscsictl add session '{}'".format(nickname), ISCSICTL_COMMAND_TIMEOUT_SECONDS
    )


# ---------------------------------------------------------------------------
# Connection planning (shared by --dry-run and the real execution path)
# ---------------------------------------------------------------------------

class VolumeConnectionPlan(object):
    __slots__ = ("volume_name", "target_name", "target_address", "nicknames")

    def __init__(self, volume_name, target_name, target_address, nicknames):
        self.volume_name = volume_name
        self.target_name = target_name
        self.target_address = target_address
        self.nicknames = nicknames


def build_connection_plan(
    elastic_san_subscription,
    resource_group_name,
    elastic_san_name,
    volume_group_name,
    volume_names,
    number_of_sessions,
    enable_zonal_affinity=False,
):
    """Resolve targets and compute the deterministic nickname set for every
    volume. This performs only read-only discovery (IMDS, Azure CLI) and pure
    computation -- no filesystem or iscsictl calls -- so it is identical for
    --dry-run and the real execution path."""
    physical_zone = (
        resolve_physical_zone(elastic_san_subscription, resource_group_name, elastic_san_name)
        if enable_zonal_affinity
        else None
    )

    plans = []
    for volume_name in volume_names:
        target_iqn, target_hostname, target_port = get_volume_storage_target(
            elastic_san_subscription,
            resource_group_name,
            elastic_san_name,
            volume_group_name,
            volume_name,
        )
        if enable_zonal_affinity:
            target_iqn = decorate_target_iqn(target_iqn, physical_zone)

        target_name = validate_config_scalar(target_iqn, "Target IQN for '{}'".format(volume_name))
        target_address = validate_config_scalar(
            "{}:{}".format(target_hostname, target_port),
            "Target address for '{}'".format(volume_name),
        )
        nicknames = [
            build_nickname(volume_group_name, volume_name, session_index)
            for session_index in range(1, number_of_sessions + 1)
        ]
        plans.append(VolumeConnectionPlan(volume_name, target_name, target_address, nicknames))
    return plans


def render_full_managed_block(plans):
    entries = [
        ManagedConfigEntry(nickname, plan.target_name, plan.target_address)
        for plan in plans
        for nickname in plan.nicknames
    ]
    return render_managed_block(entries)


def describe_plan(plans, number_of_sessions):
    lines = []
    for plan in plans:
        lines.append(
            "{} -> target {} at {} ({} session(s), nicknames: {})".format(
                plan.volume_name,
                plan.target_name,
                plan.target_address,
                number_of_sessions,
                ", ".join(plan.nicknames),
            )
        )
    return lines


# ---------------------------------------------------------------------------
# Execution path (mutating)
# ---------------------------------------------------------------------------

def add_sessions_for_volume(plan, config_path, desired_sessions):
    existing_sessions = list_iscsi_sessions()
    existing_count = count_matching_sessions(existing_sessions, plan.target_name, plan.target_address)

    if existing_count > desired_sessions:
        raise ElasticSanConnectError(
            "{}: found {} existing session(s) to {} ({}), which exceeds the requested {} "
            "session(s). This script does not remove sessions -- reconcile the discrepancy "
            "manually (raise --num-of-sessions to match, or disconnect the extras yourself with "
            "'iscsictl -L -v' and 'iscsictl -R') and re-run.".format(
                plan.volume_name,
                existing_count,
                plan.target_name,
                plan.target_address,
                desired_sessions,
            )
        )

    if existing_count == desired_sessions:
        print(
            "{} [{}]: Skipped -- {} session(s) already established".format(
                plan.volume_name, plan.target_name, existing_count
            )
        )
        return

    for nickname in plan.nicknames[existing_count:]:
        add_iscsi_session(nickname, config_path)

    refreshed_sessions = list_iscsi_sessions()
    refreshed_count = count_matching_sessions(
        refreshed_sessions, plan.target_name, plan.target_address
    )
    if refreshed_count < desired_sessions:
        raise ElasticSanConnectError(
            "{}: expected {} session(s) to {} ({}) after connecting, but 'iscsictl -L -v' shows "
            "only {}. Investigate manually with 'iscsictl -L -v' before retrying.".format(
                plan.volume_name, desired_sessions, plan.target_name, plan.target_address, refreshed_count
            )
        )
    print(
        "{} [{}]: Connected with {} session(s)".format(
            plan.volume_name, plan.target_name, desired_sessions
        )
    )


def execute_connection_plan(plans, config_path, number_of_sessions):
    check_freebsd_mutation_prerequisites()
    ensure_iscsid_enabled_and_running()

    existing_content_bytes, existed, original_stat = read_config_file(config_path)
    backup_path = backup_config(config_path, existing_content_bytes, existed)

    new_managed_block = render_full_managed_block(plans)
    new_content = compute_new_config_content(existing_content_bytes, new_managed_block)
    write_config_atomically(config_path, new_content, original_stat)

    try:
        for plan in plans:
            add_sessions_for_volume(plan, config_path, number_of_sessions)
    except (ElasticSanConnectError, OSError) as error:
        restore_config_from_backup(config_path, backup_path, existed, original_stat)
        raise ElasticSanConnectError(
            "Failed while establishing iSCSI sessions; restored {} to its pre-run state. "
            "No previously-established sessions were removed. Original error: {}".format(
                config_path, error
            )
        )


