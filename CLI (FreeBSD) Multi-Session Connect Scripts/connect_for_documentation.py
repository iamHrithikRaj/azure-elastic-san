def check_az_cli_available():
    """Confirm 'az' is on PATH and the 'elastic-san' extension is installed.

    Azure CLI on FreeBSD is provided by the FreeBSD Ports Collection /
    community packages (e.g. sysutils/py-azure-cli); it is not part of
    Microsoft's first-class supported install matrix. This function verifies
    the elastic-san extension is present, which is the most that can be
    checked programmatically -- broader compatibility must still be
    validated by the operator.
    """
    if shutil.which("az") is None:
        raise ElasticSanConnectError(
            "Azure CLI ('az') was not found on PATH. On FreeBSD, Azure CLI is provided by the "
            "FreeBSD Ports Collection / community packages (e.g. sysutils/py-azure-cli) and is "
            "not part of Microsoft's first-class supported install matrix "
            "(https://learn.microsoft.com/en-us/cli/azure/install-azure-cli-linux). Install it "
            "and 'az login', then re-run."
        )
    extension_names = _run_az_command(
        ["az", "extension", "list", "--query", "[].name", "--output", "tsv"],
        "Azure CLI extension inventory",
    )
    installed = {name.strip() for name in extension_names.splitlines() if name.strip()}
    if "elastic-san" not in installed:
        raise ElasticSanConnectError(
            "The Azure CLI 'elastic-san' extension is not installed. Because Azure CLI on "
            "FreeBSD is community-provided and not on Microsoft's first-class install matrix, "
            "extension compatibility is not verified upstream and must be checked manually. "
            "Run 'az extension add -n elastic-san', confirm 'az elastic-san volume show --help' "
            "works, and re-run this script."
        )


def check_freebsd_mutation_prerequisites():
    """Preflight required before any mutating action. Not run for --dry-run."""
    if os.geteuid() != 0:
        raise ElasticSanConnectError(
            "This action modifies {} and iSCSI session state, and must be run as root "
            "(re-run under su/doas or another privileged shell). Use --dry-run to preview a "
            "plan without root.".format(DEFAULT_ISCSI_CONF_PATH)
        )
    missing_tools = [tool for tool in REQUIRED_FREEBSD_TOOLS if shutil.which(tool) is None]
    if missing_tools:
        raise ElasticSanConnectError(
            "Required FreeBSD tool(s) not found on PATH: {}. This script targets FreeBSD 13+ "
            "native iSCSI tooling (iscsictl/service/sysrc) only; it does not use iscsiadm, "
            "systemd, or Linux package managers.".format(", ".join(missing_tools))
        )
    if not os.path.exists(ISCSI_DEVICE_NODE):
        raise ElasticSanConnectError(
            "{} was not found, so the FreeBSD iSCSI initiator kernel driver does not appear to "
            "be loaded. Use a GENERIC (or equivalent) kernel with the iscsi_initiator driver, "
            "or load it explicitly ('kldload iscsi', or iscsi_load=\"YES\" in "
            "/boot/loader.conf) before retrying.".format(ISCSI_DEVICE_NODE)
        )


