"""Standalone Azure Elastic SAN connect script for stock FreeBSD 13+.

This is a separate implementation from the Linux connect script in
"CLI (Linux) Multi-Session Connect Scripts". FreeBSD uses a different iSCSI
initiator stack (iscsid/iscsictl/iscsi.conf, sysrc/service) than Linux
(open-iscsi/iscsiadm, distro package managers), so the two scripts are kept
independent rather than sharing a code path.

Prerequisites (see README.md in this directory for full detail):
    * FreeBSD 13 or later with the native iSCSI initiator
      (iscsi(4)/iscsid(8)/iscsictl(8)) available -- /dev/iscsi must exist.
    * Python 3.
    * Azure CLI ('az') with the 'elastic-san' extension. On FreeBSD, Azure
      CLI is provided by the FreeBSD Ports Collection / community packages
      (e.g. sysutils/py-azure-cli) and is NOT part of Microsoft's
      first-class supported install matrix
      (https://learn.microsoft.com/en-us/cli/azure/install-azure-cli-linux).
      This script verifies the 'elastic-san' extension is present but cannot
      verify upstream compatibility beyond that -- validate it yourself.
    * Root privileges for any mutating action (writing /etc/iscsi.conf,
      enabling/starting iscsid, adding iSCSI sessions). --dry-run does not
      require root and performs no mutation.

This script intentionally does NOT:
    * call iscsiadm, systemd, or any Linux package manager;
    * call 'iscsictl -R -a' or otherwise remove/tear down sessions;
    * restart the iscsid service or touch sessions it did not create;
    * assemble gmultipath devices (session creation is not multipath device
      assembly -- see README.md).
"""

