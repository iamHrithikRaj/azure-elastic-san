def list_iscsi_sessions():
    """Parse 'iscsictl -L -v' into a list of per-session field dicts (keys
    such as 'Target name', 'Target portal', 'Session state'). The nickname
    used to add a session is not part of the kernel's session state and is
    therefore not recoverable from this listing. Sessions are correlated by
    Target name only because an iSCSI TargetAddress redirect can legitimately
    change Target portal after login."""
    output = _run_command(
        ["iscsictl", "-L", "-v"], "iscsictl session listing", AZ_CLI_TIMEOUT_SECONDS
    )
    return _parse_iscsictl_verbose_sessions(output)


def _parse_iscsictl_verbose_sessions(output):
    sessions = []
    fields = {}

    def append_session():
        if not fields:
            return
        required_fields = ("Target name", "Target portal", "Session state")
        missing_fields = [field for field in required_fields if field not in fields]
        if missing_fields:
            raise ElasticSanConnectError(
                "Could not safely parse 'iscsictl -L -v': a session block is missing {}".format(
                    ", ".join(missing_fields)
                )
            )
        sessions.append(dict(fields))

    for line in output.splitlines() + [""]:
        if not line.strip():
            append_session()
            fields = {}
            continue
        if ":" not in line:
            continue
        label, _, value = line.partition(":")
        label = label.strip()
        if label == "Session ID" and fields:
            append_session()
            fields = {}
        fields[label] = value.strip()
    return sessions


def sessions_for_target(sessions, target_name):
    return [
        session for session in sessions if session.get("Target name") == target_name
    ]


def session_is_connected(session):
    return (
        session.get("Session state", "").strip().lower() == "connected"
        and session.get("Enable", "Yes").strip().lower() not in ("no", "off", "disabled")
    )


def add_iscsi_session(nickname, config_path):
    command = [
        "iscsictl",
        "-A",
        "-n",
        nickname,
        "-c",
        config_path,
    ]
    _run_command(
        command, "iscsictl add session '{}'".format(nickname), ISCSICTL_COMMAND_TIMEOUT_SECONDS
    )


def wait_for_connected_session(
    target_name,
    timeout=SESSION_READY_TIMEOUT_SECONDS,
    poll_interval=SESSION_POLL_INTERVAL_SECONDS,
    monotonic=None,
    sleep=None,
):
    """Poll only *target_name* until a connected session is visible."""
    monotonic = time.monotonic if monotonic is None else monotonic
    sleep = time.sleep if sleep is None else sleep
    deadline = monotonic() + timeout
    while True:
        matching_sessions = sessions_for_target(list_iscsi_sessions(), target_name)
        if any(session_is_connected(session) for session in matching_sessions):
            return
        now = monotonic()
        if now >= deadline:
            raise ElasticSanConnectError(
                "Timed out after {} seconds waiting for target '{}' to become Connected. "
                "The iscsictl add request was already submitted and may still create or leave "
                "a live session; inspect 'iscsictl -L -v' before retrying.".format(
                    timeout, target_name
                )
            )
        sleep(min(poll_interval, deadline - now))


